// Builds site/dashfilm/console.css: the dashboard's own stylesheets (dashboard/console.css + atlas-console.css) scoped
// under .dfx, so the overview page's dashboard film renders with the real console styles and nothing leaks out.
// Light theme only (the overview page is light). Run after changing the console's CSS:  node site/dev/scope-console.mjs
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const SITE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => fs.readFileSync(path.join(SITE, f), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const S = '.dfx';
const scopeSel = (sel) => sel.split(',').map((s) => {
  s = s.trim(); if (!s) return s;
  if (/^(:root|html|body)$/.test(s)) return S;
  if (/^(html|body)\b/.test(s)) return s.replace(/^(html|body)/, S);
  if (s.startsWith('::selection')) return `${S} ${s}`;
  return `${S} ${s}`;
}).join(',');
// walk the stylesheet: rules get scoped; @media keeps its query and scopes inside; dark-mode blocks and @keyframes names stay
function scope(css) {
  let out = '', i = 0;
  while (i < css.length) {
    const open = css.indexOf('{', i); if (open < 0) break;
    const head = css.slice(i, open).trim();
    // find the matching close brace
    let d = 1, j = open + 1; while (j < css.length && d) { if (css[j] === '{') d++; else if (css[j] === '}') d--; j++; }
    const body = css.slice(open + 1, j - 1);
    if (head.startsWith('@media')) { if (!/prefers-color-scheme\s*:\s*dark|max-width/.test(head)) out += `${head}{${scope(body)}}`; }
    else if (head.startsWith('@keyframes') || head.startsWith('@font-face')) out += `${head}{${body}}`;
    else if (head.startsWith('@')) out += `${head}{${scope(body)}}`;
    else out += `${scopeSel(head)}{${body}}`;
    i = j;
  }
  return out;
}
const css = scope(read('dashboard/console.css')) + '\n' + scope(read('dashboard/atlas-console.css'))
  // the console fills the viewport; inside the film it fills the window
  .replace(/100svh/g, '100%')
  // the film moves the current page by class, not by aria-current (it isn't a real nav)
  .replace(/\.nav-l a\[aria-current(="page")?\]/g, '.nav-l a.is-cur');
fs.writeFileSync(path.join(SITE, 'dashfilm/console.css'), `/* generated by site/dev/scope-console.mjs from dashboard/console.css + atlas-console.css. Don't edit. */\n${css}\n`);
console.log('wrote dashfilm/console.css', css.length, 'bytes');
