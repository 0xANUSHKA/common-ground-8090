// Permission tests against the real API on a fresh local database: invites, kicking, revoking, removing companies,
// fund and company sharing settings, muting, deleting. `npm test` (from site/). Exits non-zero if anything fails.
import { start } from './serve.mjs';
const { url: B, close } = await start({ port: 0, quiet: true });
const jar = {}; let failed = 0;
const login = async (n) => { const r = await fetch(`${B}/dev-login?as=${n}&gh=${n}-gh`, { redirect: 'manual' }); jar[n] = r.headers.get('set-cookie').split(';')[0]; };
const p = async (n, m, path, body) => { const r = await fetch(`${B}/api/${path}`, { method: m, headers: { cookie: jar[n], 'content-type': 'application/json' }, body: body ? JSON.stringify(body) : m === 'GET' ? undefined : '{}' }); const d = await r.json(); return r.ok ? d : { ERR: r.status, ...d }; };
const ok = (label, cond, extra = '') => { if (!cond) failed++; console.log(cond ? 'PASS' : 'FAIL', label, extra); };
for (const n of ['connor', 'nush', 'theo', 'maya']) await login(n);
const F = (await p('connor', 'POST', 'orgs', { kind: 'fund', name: 'Social Capital', site: 'socialcapital.com' })).org.id;
const CI = (await p('connor', 'POST', `orgs/${F}/invites`, { kind: 'company' })).invite.code;
const SD = (await p('nush', 'POST', `invites/${CI}/accept`, { companyName: 'Saildrone', site: 'saildrone.com' })).orgId;
const PM = (await p('maya', 'POST', `invites/${CI}/accept`, { companyName: 'Palmetto', site: 'palmetto.com' })).orgId;
const MI = (await p('nush', 'POST', `orgs/${SD}/invites`, { kind: 'member' })).invite.code;
await p('theo', 'POST', `invites/${MI}/accept`);
const T = (await p('nush', 'POST', 'tools', { name: 'telemetry-inspector', orgId: SD })).tool.id;
await p('nush', 'POST', `tools/${T}/grants`, { orgId: SD });
const pre = await p('nush', 'POST', `tools/${T}/grants`, { userId: 'local_maya', companyId: PM });
ok('portfolio share blocked before mapping', pre.ERR === 403, pre.error);
const map = { source: 'x', binding: { timeColumn: 't', signalColumn: 'v', cadenceSeconds: 60 }, result: { state: 'verified', detail: 'ok' } };
await p('nush', 'PATCH', `orgs/${SD}`, { mapping: map }); await p('maya', 'PATCH', `orgs/${PM}`, { mapping: map });
const post = await p('nush', 'POST', `tools/${T}/grants`, { userId: 'local_maya', companyId: PM });
ok('portfolio share after mapping', !!post.grant, post.error);
const names = async (n) => (await p(n, 'GET', 'shared')).shared.map((s) => `${s.tool.name}/${s.grant.scope}`);
ok('theo receives team share', (await names('theo')).includes('telemetry-inspector/team'));
ok('maya receives portfolio share', (await names('maya')).includes('telemetry-inspector/portfolio'));
await p('maya', 'PATCH', `orgs/${PM}`, { settings: { receive: 'company' } });
ok('company receive=company blocks portfolio', (await names('maya')).length === 0);
await p('maya', 'PATCH', `orgs/${PM}`, { settings: { receive: 'portfolio' } });
await p('connor', 'PATCH', `orgs/${F}`, { settings: { crossCompany: false } });
ok('fund crossCompany off blocks', (await names('maya')).length === 0);
await p('connor', 'PATCH', `orgs/${F}`, { settings: { crossCompany: true } });
ok('back on', (await names('maya')).length === 1);
const fv = await p('connor', 'GET', `orgs/${F}`);
ok('fund sees companies joined', fv.companies.every((c) => c.status === 'joined') && fv.companies.length === 2, JSON.stringify(fv.companies.map((c) => c.name + ':' + c.status)));
const cv = await p('connor', 'GET', `orgs/${SD}`);
ok('fund admin views company', cv.myRole === 'fund' && cv.members.length === 2);
ok('member role toggle', !!(await p('nush', 'PATCH', `orgs/${SD}/members/local_theo`, { receiver: false })).membership);
ok('receiver off hides team share', !(await names('theo')).length);
await p('nush', 'PATCH', `orgs/${SD}/members/local_theo`, { receiver: true });
ok('kick theo', (await p('nush', 'DELETE', `orgs/${SD}/members/local_theo`)).ok);
ok('kicked theo sees nothing', !(await names('theo')).length);
ok('kicked theo cannot open org', (await p('theo', 'GET', `orgs/${SD}`)).ERR === 404);
ok('invite turn off', (await p('nush', 'DELETE', `invites/${MI}`)).ok);
ok('dead invite rejected', (await p('theo', 'POST', `invites/${MI}/accept`)).ERR === 404);
ok('fund removes palmetto', (await p('connor', 'DELETE', `orgs/${F}/companies/${PM}`)).ok);
ok('palmetto loses portfolio share', !(await names('maya')).length);
ok('owner cannot demote last owner', (await p('nush', 'PATCH', `orgs/${SD}/members/local_nush`, { role: 'member' })).ERR === 400);
ok('remove tool', (await p('nush', 'DELETE', `tools/${T}`)).ok);
const C = (await p('theo', 'POST', 'orgs', { kind: 'circle', name: 'Weekend hackers' })).org.id;
const CM = (await p('theo', 'POST', `orgs/${C}/invites`, { kind: 'member' })).invite.code;
await p('maya', 'POST', `invites/${CM}/accept`);
const PT = (await p('theo', 'POST', 'tools', { name: 'csv-sanity' })).tool.id;
await p('theo', 'POST', `tools/${PT}/grants`, { orgId: C });
ok('circle share reaches maya', (await names('maya')).includes('csv-sanity/circle'));
await p('maya', 'PATCH', 'me', { pref: { mode: 'portfolio', muted: ['local_theo'] } });
ok('mute hides', !(await names('maya')).length);
await p('maya', 'PATCH', 'me', { pref: { mode: 'portfolio', muted: [] } });
ok('maya leaves circle', (await p('maya', 'DELETE', `orgs/${C}/members/local_maya`)).ok && !(await names('maya')).length);
ok('non-owner cannot delete org', [403, 404].includes((await p('nush', 'DELETE', `orgs/${F}`)).ERR));
ok('fund owner deletes fund', (await p('connor', 'DELETE', `orgs/${F}`)).ok);
const sd2 = await p('nush', 'GET', `orgs/${SD}`); ok('company unaffiliated after fund delete', sd2.org.status === 'unaffiliated' && !sd2.org.fundId);
ok('cross-site POST blocked', (await (await fetch(`${B}/api/orgs`, { method: 'POST', headers: { cookie: jar.nush, 'content-type': 'application/json', origin: 'https://evil.example' }, body: '{"kind":"circle","name":"x"}' })).status) === 403);
ok('signed-out me is 401', (await fetch(`${B}/api/me`)).status === 401);
close();
console.log(failed ? `${failed} failed` : 'All passed');
process.exit(failed ? 1 : 0);
